const SCENE_DIAGNOSTIC_KEYS = [
  'sceneObjectRequired', 'sceneSchemaUnsupported', 'sceneIdInvalid', 'sceneNameLength', 'sceneDurationRange',
  'keyframeRequired', 'keyframeCountInvalid', 'keyframeTimesInvalid', 'keyframeEasingInvalid',
  'keyframeTargetsRequired', 'finalKeyframeInvalid',
  'scenarioSchemaUnsupported',
  'scenarioSimulationRequired',
  'scenarioCabinRequired',
  'scenarioDuplicateZones',
  'scenarioDuplicateScenes',
  'scenarioActiveSceneMismatch',
  'scenarioTooLarge', 'scenarioIntensityInvalid', 'scenarioCabinBounds',
  'scenarioCabinLayoutUnknown', 'scenarioProvenanceMismatch',
] as const;

export function studioSceneDiagnostic(locale: AppLocale, error: unknown, fallback: StudioCopyKey): string {
  if (!(error instanceof Error)) return studioText(locale, fallback);
  const key = SCENE_DIAGNOSTIC_KEYS.find((candidate) => STUDIO_COPY.en[candidate] === error.message);
  if (key) return studioText(locale, key);

  const target = /^Invalid (cabin fixture )?RGBW target for (.+)\.$/.exec(error.message);
  if (target) {
    return studioText(locale, target[1] ? 'fixtureTargetInvalid' : 'zoneTargetInvalid')
      .replace('{id}', () => target[2]);
  }
  const zoneCount = /^Scenario package must contain exactly (\d+) cabin zones\.$/.exec(error.message);
  if (zoneCount) return studioText(locale, 'scenarioZoneCount').replace('{count}', zoneCount[1]);

  const sceneCount = /^Scenario package must include 1–(\d+) scenes\.$/.exec(error.message);
  if (sceneCount) return studioText(locale, 'scenarioSceneCount').replace('{count}', sceneCount[1]);

  const zoneId = /^Zone (\d+) has an unknown zone ID\.$/.exec(error.message);
  if (zoneId) return studioText(locale, 'scenarioUnknownZone').replace('{id}', zoneId[1]);

  const zoneFade = /^Zone (.+) fade duration must be between 0 and 30 seconds\.$/.exec(error.message);
  if (zoneFade) return studioText(locale, 'scenarioZoneFade').replace('{id}', () => zoneFade[1]);

  const zoneRgbw = /^Zone (.+) needs RGBW channel values\.$/.exec(error.message);
  if (zoneRgbw) return studioText(locale, 'scenarioZoneRgbw').replace('{id}', () => zoneRgbw[1]);

  const cabinNumber = /^Cabin profile (\w+) must be a finite number\.$/.exec(error.message);
  if (cabinNumber) return studioText(locale, 'scenarioCabinNumber').replace('{field}', cabinNumber[1]);

  const channelValue = /^Zone (.+) has an invalid ([RGBW]) value\.$/.exec(error.message);
  if (channelValue) {
    return studioText(locale, 'scenarioChannelInvalid')
      .replace('{channel}', channelValue[2])
      .replace('{id}', () => channelValue[1]);
  }

  return error.message;
}
