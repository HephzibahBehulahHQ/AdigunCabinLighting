export type AppLocale = keyof typeof STUDIO_COPY;
export type StudioCopyKey = keyof typeof STUDIO_COPY.en;

export function readAppLocale(): AppLocale {
  try {
    const saved = localStorage.getItem(APP_LOCALE_KEY);
    return saved && Object.hasOwn(STUDIO_COPY, saved) ? saved as AppLocale : 'en';
  } catch { return 'en'; }
}

export function saveAppLocale(locale: AppLocale): void {
  try { localStorage.setItem(APP_LOCALE_KEY, locale); } catch { /* Keep the current page usable when storage is disabled. */ }
}

export function studioText(locale: AppLocale, key: StudioCopyKey): string {
  return STUDIO_COPY[locale][key] ?? STUDIO_COPY.en[key];
}

