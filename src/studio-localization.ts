export function studioZoneDetail(locale: AppLocale, zone: Pick<ZoneState, 'id' | 'detail'>): string {
  if (locale === 'en') return zone.detail;

  const meshNode = /^Named GLB mesh node: (.+)$/.exec(zone.detail);
  if (meshNode) return studioText(locale, 'glbMeshEvidence').replace('{node}', () => meshNode[1]);

  const locatorNode = /^Named GLB locator node: (.+); authored transform, no fixture mesh$/.exec(zone.detail);
  if (locatorNode) return studioText(locale, 'glbLocatorEvidence').replace('{node}', () => locatorNode[1]);

  const sidewall = /^(\d+) named fixture meshes; (\d+) modeled (left|right)-sidewall light strip mesh$/.exec(zone.detail);
  if (sidewall) {
    const side = sidewall[3] === 'left' ? 'left_sidewall' : 'right_sidewall';
    return studioText(locale, 'sidewallMeshEvidence')
      .replace('{fixtures}', sidewall[1])
      .replace('{strips}', sidewall[2])
      .replace('{side}', ZONE_NAMES[side][locale]);
  }

  const countedComponents = /^(\d+) (.+)$/.exec(zone.detail);
  const componentCopy = countedComponents && Object.hasOwn(COUNTED_COMPONENTS, countedComponents[2])
    ? COUNTED_COMPONENTS[countedComponents[2]]
    : undefined;
  if (countedComponents && componentCopy) {
    return componentCopy[locale].replace('{count}', countedComponents[1]);
  }

  const id = zone.id as ZoneId;
  return Object.hasOwn(ZONE_DETAILS, id) && zone.detail === ZONE_INFO[id].detail
    ? ZONE_DETAILS[id][locale]
    : zone.detail;
}

